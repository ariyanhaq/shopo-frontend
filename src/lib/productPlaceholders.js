/**
 * Returns a dynamic product name placeholder based on shop business type and language.
 */
export function getProductPlaceholder(businessType, lang = 'en') {
  const type = (businessType || '').toLowerCase().trim();

  for (const [key, val] of Object.entries(BUSINESS_PRODUCT_EXAMPLES)) {
    if (type.includes(key)) {
      return lang === 'bn' ? val.productBn : val.productEn;
    }
  }

  return lang === 'bn'
    ? 'যেমন: অরেক্স খাতা, সুতি শার্ট, মিনিকেট চাল'
    : 'e.g. Aurex Khata, Cotton Shirt, Miniket Rice';
}

/**
 * Returns a dynamic category placeholder based on shop business type and language.
 */
export function getCategoryPlaceholder(businessType, lang = 'en') {
  const type = (businessType || '').toLowerCase().trim();

  for (const [key, val] of Object.entries(BUSINESS_PRODUCT_EXAMPLES)) {
    if (type.includes(key)) {
      return lang === 'bn' ? val.categoryBn : val.categoryEn;
    }
  }

  return lang === 'bn'
    ? 'ক্যাটাগরির নাম (যেমন: খাতা, খাদ্যদ্রব্য, পোশাক)'
    : 'Category name (e.g. Stationery, Beverages, Apparel)';
}
